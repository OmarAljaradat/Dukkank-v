        const badge = BADGES[i % BADGES.length];
        const prod = PRODUCTS[i % PRODUCTS.length];
        const text = FEEDBACKS[i % FEEDBACKS.length];

        list.push({
            id: `rev-gen-${i}`,
            name: `${fn} ${ln} ${init}`,
            badge: badge,
            rating: i % 14 === 0 ? 4 : 5, // 93% 5 stars, 7% 4 stars
            text: text,
            item: prod,
        });
